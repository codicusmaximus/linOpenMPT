// linOpenMPT compatibility layer: <gdipluspixelformats.h>. Upstream
// includes it inside namespace Gdiplus, as the Windows SDK expects. Image
// loading itself (upstream's Image.cpp, on GDI+) is replaced by Qt.
#pragma once
using PixelFormat = INT;
#define PixelFormatIndexed 0x00010000
#define PixelFormatGDI 0x00020000
#define PixelFormatAlpha 0x00040000
#define PixelFormatPAlpha 0x00080000
#define PixelFormatCanonical 0x00200000
#define PixelFormat24bppRGB (8 | (24 << 8) | PixelFormatGDI)
#define PixelFormat32bppRGB (9 | (32 << 8) | PixelFormatGDI)
#define PixelFormat32bppARGB (10 | (32 << 8) | PixelFormatAlpha | PixelFormatGDI | PixelFormatCanonical)
#define PixelFormat32bppPARGB (11 | (32 << 8) | PixelFormatAlpha | PixelFormatPAlpha | PixelFormatGDI)
using ARGB = DWORD;
using ARGB64 = ULONGLONG;
#define ALPHA_SHIFT 24
#define RED_SHIFT 16
#define GREEN_SHIFT 8
#define BLUE_SHIFT 0
#define ALPHA_MASK ((ARGB)0xff << ALPHA_SHIFT)
